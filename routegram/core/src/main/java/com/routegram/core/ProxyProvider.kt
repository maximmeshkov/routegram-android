package com.routegram.core

/**
 * Источник рабочей точки входа для обхода блокировок.
 *
 * Это главная точка расширения модуля: tg-ws-proxy, парсинг и автовыбор
 * внешних прокси и любые другие стратегии реализуют ЭТОТ интерфейс,
 * ничего не зная друг о друге. Заменить механизм обхода = подставить
 * другую реализацию [ProxyProvider], остальной код не меняется.
 */
interface ProxyProvider {
    /**
     * Получить рабочую конфигурацию прокси.
     *
     * `suspend` (≈ async в C#) — потому что получение/проверка прокси
     * может ходить в сеть и не должна блокировать поток.
     *
     * @return конфигурация, либо `null` если прокси не нужен/не найден.
     */
    suspend fun obtain(): ProxyConfig?
}
